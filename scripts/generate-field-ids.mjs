import { readFile, writeFile } from 'node:fs/promises';

// The canonical JSON is the only source. Do not infer runtime value types from
// metadata: a documented format does not prove that a returned value is valid.
export async function generateFieldIds() {
  const document = JSON.parse(await readFile(new URL('../protocol/fields.json', import.meta.url), 'utf8'));
  const explicit = Object.keys(document.entries).map(Number).sort((a, b) => a - b);
  const known = new Set(explicit);
  for (const range of document.ranges) {
    for (let code = range.from; code <= range.to; code++) known.add(code);
  }
  const union = (codes) => codes.join(' | ');
  const output = `// Generated by scripts/generate-field-ids.mjs from protocol/fields.json. Do not edit.\n` +
    `export type ExplicitFieldId = ${union(explicit)};\n` +
    `/** Documented IDs, including context-dependent ranges; never a whitelist. */\n` +
    `export type KnownFieldId = ${union([...known].sort((a, b) => a - b))};\n`;
  await writeFile(new URL('../packages/core/src/field-ids.generated.ts', import.meta.url), output);
}
